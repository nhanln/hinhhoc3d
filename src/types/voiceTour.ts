export interface VoiceTourStep {
  id: string;
  order: number;
  title: string;
  speechText: string;
  captionText: string;
  targetType: 'overview' | 'vertex' | 'edge' | 'face';
  targetId?: string; // Vertex id like 'S', 'A', 'B' or Edge id like 'S-A', 'A-B'
  targetLabel?: string;
  cameraPreset?: 'sgk' | 'top' | 'front' | 'side' | 'custom';
  durationSeconds?: number;
  noteId?: string; // Attached sticky note ID if applicable
}

export interface VoiceTourScript {
  id: string;
  title: string;
  shapeType: string;
  createdAt: string;
  autoGenerated: boolean;
  steps: VoiceTourStep[];
}

export interface VoiceTourSettings {
  rate: number; // 0.8, 1.0, 1.2
  pitch: number;
  volume: number;
  autoAdvance: boolean; // Auto advance to next step when speech ends
  pauseBetweenSteps: number; // seconds (default: 1.5)
  showCaptions: boolean;
  highlightIn3D: boolean;
}
